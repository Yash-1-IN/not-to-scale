"""Builds the fast-loading index.html from dev.html.

    python tools/build.py           # rebuild index.html and js/bundle.<hash>.js
    python tools/build.py --check   # exit 1 if they are out of date (nothing is written)

dev.html is the page you edit: it lists every script (js/*.js and pages/*.js) one by one, which is easy to
work with. index.html is generated from it: the same page, but all of the book's own scripts are joined
into one file, js/bundle.<hash>.js (the hash is in the file name, so browsers never keep an old copy).
That turns ~100 small requests into one, which is noticeably faster on a real connection. Both files work
by double-clicking, and both run the self-test with ?test.

After changing any script, CSS or dev.html, run this before testing index.html or committing.
"""
import glob
import hashlib
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)

SCRIPT = re.compile(r'^[ \t]*<script src="([^"]+)"></script>[ \t]*\r?\n', re.M)
BANNER = ("<!-- GENERATED by tools/build.py from dev.html. Don't edit this file: edit dev.html (or the scripts)\n"
          "     and run `python tools/build.py`. -->\n")


def read(path):
    with open(path, encoding="utf-8", newline="") as f:
        return f.read().replace("\r\n", "\n")


def build():
    html = read("dev.html")
    local = []                       # the book's own scripts, in order
    first = last = None
    for m in SCRIPT.finditer(html):
        if m.group(1).startswith(("http://", "https://")):
            continue
        local.append(m.group(1))
        first = m.start() if first is None else first
        last = m.end()
    if not local:
        sys.exit("no local scripts found in dev.html")
    # every script tag between the first and last local one must be local (so joining them keeps the order)
    between = SCRIPT.findall(html[first:last])
    if between != local:
        sys.exit("dev.html mixes external and local scripts in the middle of the list; keep external ones before it")
    missing = [p for p in local if not os.path.exists(p)]
    if missing:
        sys.exit("dev.html lists scripts that don't exist: " + ", ".join(missing))

    parts = []
    for p in local:
        parts.append("/* ---- " + p + " ---- */\n" + read(p).rstrip() + "\n")
    bundle = ";\n".join(parts)
    digest = hashlib.sha1(bundle.encode("utf-8")).hexdigest()[:8]
    name = "js/bundle." + digest + ".js"

    css = hashlib.sha1(read("css/styles.css").encode("utf-8")).hexdigest()[:8]
    out = html[:first] + '  <script src="' + name + '"></script>\n' + html[last:]
    out = out.replace('href="css/styles.css"', 'href="css/styles.css?v=' + css + '"')
    out = re.sub(r"(<!DOCTYPE html>\n)", lambda m: m.group(1) + BANNER, out, count=1)
    return out, name, bundle


def main():
    out, name, bundle = build()
    current = read("index.html") if os.path.exists("index.html") else ""
    stale = current != out or not os.path.exists(name)
    if "--check" in sys.argv:
        if stale:
            print("index.html / bundle are out of date: run  python tools/build.py")
            sys.exit(1)
        print("up to date:", name)
        return
    for old in glob.glob("js/bundle.*.js"):
        if old.replace("\\", "/") != name:
            os.remove(old)
    with open(name, "w", encoding="utf-8", newline="\n") as f:
        f.write(bundle)
    with open("index.html", "w", encoding="utf-8", newline="\n") as f:
        f.write(out)
    try:
        subprocess.run(["node", "--check", name], check=True, capture_output=True)
    except FileNotFoundError:
        pass                                  # no node: skip the syntax check
    except subprocess.CalledProcessError as e:
        sys.exit("the bundle has a syntax error:\n" + e.stderr.decode("utf-8", "replace"))
    print("built", name, "(%d KB)" % (len(bundle.encode("utf-8")) // 1024), "and index.html")


if __name__ == "__main__":
    main()
